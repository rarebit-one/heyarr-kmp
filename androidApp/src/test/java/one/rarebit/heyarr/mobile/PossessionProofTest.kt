        val parsed = Cert.parse(certB)
        assertEquals(2, parsed.cert.version)
        assertTrue("cert signature by usr", parsed.verify(JdkEd25519.verifier))
        assertEquals(
            "ed25519:03a107bff3ce10be1d70dd18e74bc09967e4d6309ba50d5f1ddc8664125531b8",
            parsed.cert.user.render(),
