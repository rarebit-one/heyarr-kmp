        assertEquals(
            PossessionProof.Reason.WRONG_TYPE,
            refused { PossessionProof.verify(proofA, ByteArray(32), certA, nowA + 1, JdkEd25519.verifier) },
        )
        assertThrows(IllegalArgumentException::class.java) { Cert.parse(certA) }
