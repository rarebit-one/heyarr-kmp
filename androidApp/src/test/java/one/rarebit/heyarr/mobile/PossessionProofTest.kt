    private fun devicePub(token: String) = Cert.parse(token).cert.device.bytes

    @Test fun verifyMirrorsGoWindow() {
        val pub = devicePub(certB)
        // honoured 1s before expiry; expired AT ttl (strict); honoured half a skew early; refused 2 skews early
        PossessionProof.verify(proofB, pub, certB, nowB + 119, JdkEd25519.verifier)
        assertEquals(
            PossessionProof.Reason.EXPIRED,
            refused {
                PossessionProof.verify(proofB, pub, certB, nowB + 120, JdkEd25519.verifier)
            },
        )
        PossessionProof.verify(proofB, pub, certB, nowB - 15, JdkEd25519.verifier)
        assertEquals(
            PossessionProof.Reason.NOT_YET_VALID,
            refused {
                PossessionProof.verify(
                    proofB,
                    pub,
                    certB,
                    nowB - 60,
                    JdkEd25519.verifier,
                )
            },
        )
    }

    @Test fun verifyRefusesWrongCertAndTamperedBody() {
        val pub = devicePub(certB)
        assertEquals(
            PossessionProof.Reason.WRONG_CERT,
            refused {
                PossessionProof.verify(proofB, pub, certA, nowB + 1, JdkEd25519.verifier)
            },
        )
        val flipped = proofB.substring(0, 5) + (if (proofB[5] == 'A') 'B' else 'A') + proofB.substring(6)
        assertEquals(
            PossessionProof.Reason.BAD_SIGNATURE,
            refused {
                PossessionProof.verify(
                    flipped,
                    pub,
                    certB,
                    nowB + 1,
                    JdkEd25519.verifier,
                )
            },
        )
        assertEquals(
            PossessionProof.Reason.MALFORMED,
            refused {
                PossessionProof.verify("no-dot", pub, certB, nowB + 1, JdkEd25519.verifier)
            },
        )
    }

    private fun refused(block: () -> Unit): PossessionProof.Reason =
        assertThrows(PossessionProof.Refused::class.java) { block() }.reason

    @Test fun sessionCredentialHeaderValueUnchanged() {
        assertEquals("Bearer tok", Credential.Session("tok").headerValue())
    }
